"""Actual ELF, emulated peripherals only: diagnostic radio + control equivalence.
Usage: python verify_flow_diagnostics.py --baseline <15ebe30 official_hand.elf>
"""
from pathlib import Path
import argparse, hashlib, json, random, struct
from elftools.elf.elffile import ELFFile

root=Path(__file__).resolve().parents[1]
source=Path(__file__).with_name('verify_flow_recovery.py')
ns={'__file__':str(source),'__name__':'diagnostics_offline'}
exec(compile(source.read_text(encoding='utf-8').split('m=prepared()')[0],str(source),'exec'),ns)
FlowMachine,fb=ns['FlowMachine'],ns['fb']
checks=[]
def check(name,ok):
    assert ok,name
    checks.append(name)
def poll(m,t):
    m.now(t&0xffffffff);m.call('hand_link_poll')
    m.now((t+1)&0xffffffff);m.call('hand_link_poll')
def crc(data):
    c=65535
    for b in data:
        c^=b<<8
        for _ in range(8):c=((c<<1)^(0x1021 if c&0x8000 else 0))&65535
    return c

parser=argparse.ArgumentParser()
parser.add_argument('--baseline',type=Path,required=True)
parser.add_argument('--protocol-only',action='store_true',help='Allow intentional horizontal-control changes; still compare estimator and verify wire protocol')
args=parser.parse_args()
a,b=FlowMachine(),FlowMachine()
# Replace the second emulated image with the previously flashed baseline.
b.u.mem_write(0x20000000,bytes(0x10000))
with args.baseline.open('rb') as stream:
    elf=ELFFile(stream)
    b.sym={s.name:s['st_value'] for s in elf.get_section_by_name('.symtab').iter_symbols() if s['st_value']}
    for segment in elf.iter_segments():
        if segment['p_type']=='PT_LOAD':b.u.mem_write(segment['p_vaddr'],segment.data())
b.call('pid_param_Init');b.put('ALL_flag','B',19);b.rc(1500,1500,1500,1500)
compare=['pidPositionX','pidPositionY','pidPosRateX','pidPosRateY','pidRoll','pidPitch']
rng=random.Random(20261007)
for i,t in enumerate(range(0,4801,6)):
    # Healthy motion, quality dropout, recovery, stale interval, manual switch.
    quality=20 if 900<=t<960 or 2600<=t<2630 else 80
    dx,dy=(rng.randint(-2,2),rng.randint(-2,2)) if t>400 else (0,0)
    for m in (a,b):
        if 1800<=t<1930:m.now(t)
        else:m.sample(t,quality=quality,dx=dx,dy=dy)
        if t%24==0:
            m.rc(1500,1800 if 500<t<850 else 1500,1500,1500)
            m.estimate();m.control()
    if t%24==0:
        if not args.protocol_only:
            check('control state/output identical '+str(t),all(a.get(n,'13f')==b.get(n,'13f') for n in compare))
        check('estimate identical '+str(t),all(a.get(n,'f')==b.get(n,'f') for n in
              ['flow_x_lpf_att_i','flow_y_lpf_att_i','flow_x_vel_lpf_i','flow_y_vel_lpf_i']))

# A real encoded radio response is generated by the actual polling function.
m=FlowMachine();m.put('ALL_flag','B',0);m.h('radio_ready',1)
for index,t in enumerate(range(1000,5001,50),1):
    m.now(t);m.call('hand_link_imu',1);m.sample(t,height=300,quality=80,dx=1,dy=-1);m.estimate()
    m.send(2,index);poll(m,t+20)
frames=m.radio_sent
check('no added radio transmissions',len(frames)==81)
check('one existing slot per 50ms',all(y[0]-x[0]==50 for x,y in zip(frames,frames[1:])))
check('all frame CRCs valid',all(crc(raw[:30])==int.from_bytes(raw[30:],'big') for _,raw in frames))
diag=[(t,raw) for t,raw in frames if 0x84<=raw[3]<=0x88]
base=[(t,raw) for t,raw in frames if raw[3]<0x84]
check('base acknowledgements never starved',max(y[0]-x[0] for x,y in zip(base,base[1:]))<=100)
check('no consecutive diagnostic frames',all(not(0x84<=x[1][3]<=0x88 and 0x84<=y[1][3]<=0x88) for x,y in zip(frames,frames[1:])))
for command,bound in [(0x83,300),(0x81,650),(0x82,650)]:
    times=[t for t,raw in frames if raw[3]==command]
    check('bounded ordinary reply '+hex(command),len(times)>2 and max(y-x for x,y in zip(times,times[1:]))<=bound)
groups={}
for t,raw in diag:
    words=struct.unpack('>8H',raw[10:26]);sample,stamp=words[:2]
    group=groups.setdefault(sample,{'stamp':stamp,'pages':{},'times':[]})
    check('coherent timestamp '+str(t),stamp==group['stamp'])
    check('page not duplicated '+str(t),raw[3] not in group['pages'])
    check('source age carried '+str(t),(t-stamp)&65535==int.from_bytes(raw[28:30],'big'))
    check('diagnostic reserved bytes '+str(t),raw[26:28]==b'\x01\0')
    group['pages'][raw[3]]=list(words[2:]);group['times'].append(t)
complete=[g for g in groups.values() if len(g['pages'])==5]
(root/'Output/gcc/flow-radio-replay.bin').write_bytes(b''.join(struct.pack('<I',t)+raw for t,raw in frames))
check('multiple complete snapshots',len(complete)>=5)
check('normal diagnostic sample under 1000ms',all(g['times'][-1]-g['times'][0]<1000 for g in complete))
g=complete[0]
check('ground actual RC is neutral',g['pages'][0x84][2:4]==[1500,1500])
check('quality/raw motion carried',g['pages'][0x84][0]>>8==80 and g['pages'][0x88][:2]==[1,65535])
check('no motor start from diagnostics',m.pwm()==(0,0,0,0) and all(g['pages'][0x87][2:]==[0]*4 for g in complete))

# Numeric saturation, NaN marker, signed values, and timer wrap use real Thumb code.
flag=0x2000e800
for value,scale,expected,flags in [(1.25,100,125,0),(-1.25,100,65411,0),
        (999999,10,32767,64),(-999999,10,32769,64),(float('nan'),10,32768,128)]:
    m.u.mem_write(flag,b'\0\0')
    result=m.call('fd_scaled',fb(value),fb(scale),flag)
    check('numeric conversion '+str(value),result==expected and int.from_bytes(m.u.mem_read(flag,2),'little')==flags)

report={'passed':len(checks),'failed':0,'hardware_access':False,'actual_ELF':True,
        'elf_sha256':hashlib.sha256((root/'Output/gcc/official_hand.elf').read_bytes()).hexdigest(),
        'baseline_sha256':hashlib.sha256(args.baseline.read_bytes()).hexdigest(),
        'control_equivalence_checked':not args.protocol_only,
        'normal_frames':len(base),'diagnostic_frames':len(diag),'complete_samples':len(complete),
        'sample_pages_example':g,'checks':checks}
(root/'Output/gcc/flow-diagnostics-verification.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
print(json.dumps({k:v for k,v in report.items() if k not in ('checks','sample_pages_example')}))
